  }

  fun localizedColor(colorName: String, lang: AppLanguage): String = when (lang) {
    AppLanguage.BN -> when (colorName) {
      "Yellow" -> "হলুদ (Yellow)"
      "Blue" -> "নীল (Blue)"
      "Green" -> "সবুজ (Green)"
      "Red" -> "লাল (Red)"
      "White" -> "সাদা (White)"
      "Silver/Grey" -> "সিলভার/ধূসর"
      "Black & Yellow" -> "কালো ও হলুদ"
      else -> colorName
    }
    AppLanguage.HI -> when (colorName) {
      "Yellow" -> "पीला (Yellow)"
      "Blue" -> "नीला (Blue)"
      "Green" -> "हरा (Green)"
      "Red" -> "लाल (Red)"
      "White" -> "सफ़ेद (White)"
      "Silver/Grey" -> "सिल्वर/ग्रे"
      "Black & Yellow" -> "काला और पीला"
      else -> colorName
    }
    AppLanguage.EN -> colorName
  }
}

fun stringsFor(language: AppLanguage): AppStrings = when (language) {
